def _sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _json(path):
    return json.loads(
        Path(path).read_text(encoding="utf-8"),
        object_pairs_hook=contract._pairs,
        parse_constant=lambda _: (_ for _ in ()).throw(ValueError("Nonfinite JSON")),
    )


def _jsonl(path):
    rows = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if not line.strip():
            raise ValueError("Blank manifest row")
        rows.append(json.loads(line, object_pairs_hook=contract._pairs))
    return rows


def _write_json(path, value):
    Path(path).write_text(
        json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2, allow_nan=False) + "\n",
        encoding="utf-8",
    )


def _inventory(root):
    root = Path(root).resolve(strict=True)
    result = {}
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise ValueError("Protocol package cannot contain symlinks")
        if path.is_file():
            result[path.relative_to(root).as_posix()] = _sha(path)
    return result


def _safe_package_files(root):
    """Authenticate the exact original source, including its inventory itself."""
    root = Path(root).resolve(strict=True)
    manifest_bytes = (root / "PACKAGE_SHA256.json").read_bytes()
    if hashlib.sha256(manifest_bytes).hexdigest() != ORIGINAL_PACKAGE_SHA256:
        raise ValueError("Original V1 package inventory differs from frozen authority")
    expected = json.loads(
        manifest_bytes,
        object_pairs_hook=contract._pairs,
        parse_constant=lambda _: (_ for _ in ()).throw(ValueError("Nonfinite JSON")),
    )
    actual = _inventory(root)
    if actual != {**expected, "PACKAGE_SHA256.json": ORIGINAL_PACKAGE_SHA256}:
        raise ValueError("Original V1 package content differs from frozen authority")
    return actual


def serialize_teacher_target(target: Mapping, revision: str = "v1") -> dict:
    """Preserve the teacher object and recalculate exact complete-text spans."""
    contract_for_revision(revision)
    if not isinstance(target, Mapping) or set(target) != {"text", "spans", "object"}:
        raise ValueError("Teacher must retain the original text/spans/object schema")
    obj, spans = target_spans(target["text"])
    if obj != target["object"] or spans != target["spans"]:
        raise ValueError("Original teacher text, object and spans disagree")
    if revision == "v1":
        return copy.deepcopy(dict(target))
    text = json.dumps(obj, indent=2, ensure_ascii=False)
    new_obj, new_spans = target_spans(text)
    # Preserve the original manifest mapping order as well as field coordinates.
    new_spans = {key: new_spans[key] for key in target["spans"]}
    return {"text": text, "spans": new_spans, "object": new_obj}


def teacher_target(world, query, with_work, revision: str = "v1") -> dict:
    return serialize_teacher_target(contract.support_target(world, query, with_work), revision)


def revision_config(original: Mapping, revision: str) -> dict:
    if revision not in CANDIDATES:
        raise ValueError("Candidate must be v2 or c2")
    if any(
        key in original
        for key in ("protocol_revision", "protocol_revision_reason", "teacher_serialization")
    ):
        raise ValueError("Expected the untouched V1 configuration")
    result = copy.deepcopy(dict(original))
    result.update(
        protocol_revision=revision,
        protocol_revision_reason=REVISION_REASON,
        teacher_serialization=TEACHER_SERIALIZATION,
    )
    if revision == "c2":
        result["generation"]["prefill"] = prefill_for("structured", revision)
        result["generation"]["prefill_by_protocol"] = {
            protocol: prefill_for(protocol, revision)
            for protocol in ("structured", "answer_only", "natural_work")
        }
    return result


def revision_from_config(config: Mapping) -> str:
    """Read the explicit revision, rejecting unknown or contradictory settings."""
    revision = config.get("protocol_revision", "v1")
    contract_for_revision(revision)
    if revision == "v1":
        if "teacher_serialization" in config or "protocol_revision_reason" in config:
            raise ValueError("V1 cannot carry candidate serialization metadata")
        return revision
    if (
        config.get("protocol_revision_reason") != REVISION_REASON
        or config.get("teacher_serialization") != TEACHER_SERIALIZATION
        or config.get("generation", {}).get("prefill") != prefill_for("structured", revision)
    ):
        raise ValueError("Protocol revision configuration is inconsistent")
    mapping = config.get("generation", {}).get("prefill_by_protocol")
    if revision == "c2" and mapping != {
        protocol: prefill_for(protocol, revision)
        for protocol in ("structured", "answer_only", "natural_work")
    }:
        raise ValueError("C2 must preserve separate answer-only and natural-work prefills")
    if revision == "v2" and mapping is not None:
        raise ValueError("V2 must retain the original generation configuration")
    return revision


def _semantic(value):
    return json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False
    )


def validate_revision_config(original: Mapping, candidate: Mapping, revision: str) -> None:
    if _semantic(candidate) != _semantic(revision_config(original, revision)):
        raise ValueError("Unregistered configuration change outside serialization revision")


def _equal_except(original, candidate, allowed, location):
    if set(original) != set(candidate):
        raise ValueError(f"Manifest schema changed at {location}")
    old = {k: v for k, v in original.items() if k not in allowed}
    new = {k: v for k, v in candidate.items() if k not in allowed}
    if _semantic(old) != _semantic(new):
        raise ValueError(f"Unregistered manifest change at {location}")


def validate_revision_manifests(original_dir, candidate_dir, revision: str) -> dict:
    """Prove only prompt and serialized teacher fields changed across all rows."""
    contract_for_revision(revision)
    old, new = Path(original_dir), Path(candidate_dir)
    unchanged = {}
    for name in UNCHANGED_MANIFESTS:
        if (old / name).read_bytes() != (new / name).read_bytes():
            raise ValueError("Unregistered manifest change: " + name)
        unchanged[name] = _sha(new / name)
    old_tasks = _jsonl(old / "TASKS_AUDIT_ONLY.jsonl")
    new_tasks = _jsonl(new / "TASKS_AUDIT_ONLY.jsonl")
    if len(old_tasks) != 4096 or len(new_tasks) != 4096:
        raise ValueError("The revision must preserve exactly 4096 tasks")
    changed_prompt = changed_teacher = 0
    unchanged_other_protocols = 0
    for index, (before, after) in enumerate(zip(old_tasks, new_tasks, strict=True)):
        _equal_except(before, after, {"prompt", "teacher"}, f"task {index}")
        expected_prompt = prompt_for_revision(before["prompt"], revision)
        if after["prompt"] != expected_prompt:
            raise ValueError(f"Incorrect revision prompt at task {index}")
        changed_prompt += before["prompt"] != after["prompt"]
        for protocol in ("answer_only", "natural_work"):
            if prompt_from_frozen(before["prompt"], protocol) != prompt_from_frozen(
                after["prompt"], protocol
            ):
                raise ValueError("A non-structured protocol changed")
            unchanged_other_protocols += 1
        if before["teacher"] is None:
            if after["teacher"] is not None:
                raise ValueError("Revision added teacher information to a non-support row")
            continue
        expected = {
            arm: serialize_teacher_target(target, revision)
            for arm, target in before["teacher"].items()
        }
        if _semantic(after["teacher"]) != _semantic(expected):
            raise ValueError(f"Incorrect teacher serialization or spans at task {index}")
        if after["teacher"]["PREFIX"] != after["teacher"]["EXEC"]:
            raise ValueError("PREFIX/EXEC teacher bytes must remain identical")
        changed_teacher += before["teacher"] != after["teacher"]
    old_inputs = _jsonl(old / "MODEL_INPUTS.jsonl")
    new_inputs = _jsonl(new / "MODEL_INPUTS.jsonl")
    if len(old_inputs) != 4096 or len(new_inputs) != 4096:
        raise ValueError("The revision must preserve exactly 4096 model inputs")
    for index, (before, after) in enumerate(zip(old_inputs, new_inputs, strict=True)):
        _equal_except(before, after, {"prompt"}, f"input {index}")
        if after["prompt"] != prompt_for_revision(before["prompt"], revision):
            raise ValueError(f"Incorrect revision prompt at input {index}")
        if after["prompt"] != new_tasks[index]["prompt"] or after["qid"] != new_tasks[index]["qid"]:
            raise ValueError("Model input ordering differs from task audit")
    return {
        "status": "PASS",
        "tasks": 4096,
        "model_inputs": 4096,
        "prompt_rows_changed": changed_prompt,
        "support_teacher_rows_changed": changed_teacher,
        "teacher_targets": changed_teacher * 3,
        "nonstructured_prompts_byte_identical": unchanged_other_protocols,
        "allowed_task_fields": ["prompt", "teacher.text", "teacher.spans"],
        "teacher_objects_unchanged": True,
        "unregistered_differences": 0,
        "unchanged_manifests": unchanged,
        "original_tasks_sha256": _sha(old / "TASKS_AUDIT_ONLY.jsonl"),
        "revised_tasks_sha256": _sha(new / "TASKS_AUDIT_ONLY.jsonl"),
        "original_model_inputs_sha256": _sha(old / "MODEL_INPUTS.jsonl"),
        "revised_model_inputs_sha256": _sha(new / "MODEL_INPUTS.jsonl"),
    }


def _replace_ast_node(source, name, replacement):
    nodes = [
        node
        for node in ast.parse(source).body
        if (isinstance(node, ast.FunctionDef) and node.name == name)
        or (
            isinstance(node, ast.Assign)
            and any(isinstance(t, ast.Name) and t.id == name for t in node.targets)
        )
    ]
    if len(nodes) != 1:
        raise ValueError("Original reference source has ambiguous revision anchor: " + name)
    node = nodes[0]
    lines = source.splitlines(keepends=True)
    return (
        "".join(lines[: node.lineno - 1]) + replacement + "\n" + "".join(lines[node.end_lineno :])
    )


