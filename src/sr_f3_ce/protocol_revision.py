def _run(command, cwd, log):
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE="1", PYTHONPATH="")
    result = subprocess.run(
        command, cwd=cwd, env=env, text=True, capture_output=True, check=False, timeout=300
    )
    Path(log).write_text(result.stdout + result.stderr, encoding="utf-8")
    if result.returncode:
        raise RuntimeError(f"Reference validation failed ({result.returncode}); see {log}")
    return {"argv": command, "returncode": result.returncode, "log_sha256": _sha(log)}


def verify_revision_package(plan_dir, *, source_plan_dir=None) -> dict:
    """Authenticate a candidate without trusting its self-authored inventory."""
    root = Path(plan_dir).resolve(strict=True)
    original = root / "revision_sources/v1"
    original_inventory = _safe_package_files(original)
    if source_plan_dir is not None and _safe_package_files(source_plan_dir) != original_inventory:
        raise ValueError("Supplied original package differs from retained original")
    if _sha(root / "revision_sources/REQUEST.md") != REQUEST_SHA256:
        raise ValueError("Revision request differs from explicit fixed authority")
    config = _json(root / "config/SR_F3_CE.json")
    revision = revision_from_config(config)
    if revision not in CANDIDATES:
        raise ValueError("Candidate package must explicitly select v2 or c2 serialization")
    validate_revision_config(_json(original / "config/SR_F3_CE.json"), config, revision)
    receipt = _json(root / "PROTOCOL_REVISION.json")
    if (
        receipt.get("protocol_revision") != revision
        or receipt.get("original_package_manifest_sha256") != ORIGINAL_PACKAGE_SHA256
        or receipt.get("request_sha256") != REQUEST_SHA256
        or receipt.get("status") != "CANDIDATE_CPU_VALIDATED_UNSELECTED"
        or receipt.get("decision_rule") != DECISION_RULE
    ):
        raise ValueError("Candidate receipt contradicts frozen authority")
    expected_metadata = {
        "original_plan_files": original_inventory,
        "contract_sha256": hashlib.sha256(contract_for_revision(revision).encode()).hexdigest(),
        "teacher_serialization": TEACHER_SERIALIZATION,
        "teacher_mask_serialization_id": "indent_2",
        "protocol_prefills": {
            protocol: prefill_for(protocol, revision)
            for protocol in ("structured", "answer_only", "natural_work")
        },
        "original_validation_logs_are_v1_only": True,
        "production_scorer_modified": False,
        "new_model_calls": 0,
        "new_training_steps": 0,
    }
    if any(receipt.get(key) != value for key, value in expected_metadata.items()):
        raise ValueError("Candidate provenance metadata contradicts its validated contents")
    expected_revisions = _expected_revised_files(original, revision)
    changed = set(expected_revisions) | {
        "config/SR_F3_CE.json",
        "manifests/MODEL_INPUTS.jsonl",
        "manifests/TASKS_AUDIT_ONLY.jsonl",
    }
    for name, expected in expected_revisions.items():
        if (root / name).read_text(encoding="utf-8") != expected:
            raise ValueError("Unregistered reference/document mutation: " + name)
    for name, sha in original_inventory.items():
        if name not in changed | {"PACKAGE_SHA256.json"} and _sha(root / name) != sha:
            raise ValueError("A frozen nonserialization file changed: " + name)
    difference = validate_revision_manifests(original / "manifests", root / "manifests", revision)
    if difference != receipt.get("manifest_difference"):
        raise ValueError("Candidate manifest-difference receipt is inaccurate")
    actual = _inventory(root)
    recorded = _json(root / "PACKAGE_SHA256.json")
    if actual != {**recorded, "PACKAGE_SHA256.json": _sha(root / "PACKAGE_SHA256.json")}:
        raise ValueError("Candidate package inventory does not close over every file")
    expected_extra = {
        "PROTOCOL_REVISION.json",
        "PROTOCOL_REVISION_zh.md",
        "revision_sources/REQUEST.md",
        "validation/REVISION_BUILD_STDOUT.txt",
        "validation/REVISION_REBUILD_STDOUT.txt",
        "validation/REVISION_REFERENCE_TESTS.txt",
        "validation/REVISION_CPU_CHECKS.json",
        "validation/REVISION_CONTRACT_DIFF.txt",
    }
    expected_names = (
        set(original_inventory)
        | expected_extra
        | {"revision_sources/v1/" + name for name in original_inventory}
    )
    if set(actual) != expected_names:
        raise ValueError("Candidate contains unexpected or missing package files")
    checks = _json(root / "validation/REVISION_CPU_CHECKS.json")
    if checks != receipt.get("reference_validation"):
        raise ValueError("Reference-validation receipt mismatch")
    if checks.get("byte_identical_rebuild") != _inventory(root / "manifests"):
        raise ValueError("Reference rebuild receipt differs from actual manifests")
    for label, log in (
        ("build", "REVISION_BUILD_STDOUT.txt"),
        ("rebuild", "REVISION_REBUILD_STDOUT.txt"),
        ("tests", "REVISION_REFERENCE_TESTS.txt"),
    ):
        check = checks.get(label, {})
        if check.get("returncode") != 0 or check.get("log_sha256") != _sha(
            root / "validation" / log
        ):
            raise ValueError("Reference execution log does not match its receipt")
    return {
        "status": "PASS",
        "revision": revision,
        "protocol_revision": revision,
        "package_manifest_sha256": _sha(root / "PACKAGE_SHA256.json"),
        "checked_files": recorded,
        "model_inputs_sha256": _sha(root / "manifests/MODEL_INPUTS.jsonl"),
        "request_sha256": REQUEST_SHA256,
        "original_package_manifest_sha256": ORIGINAL_PACKAGE_SHA256,
        "manifest_difference": difference,
        "read_only": True,
        "engine_gate_status": "NOT_RUN",
        "selected_for_science": False,
    }


def build_revision_candidate(source_plan, request, output_plan, revision: str) -> dict:
    """Generate and validate once in a fresh path, then atomically publish it."""
    if not __debug__:
        raise RuntimeError("Protocol revision validation cannot run with Python optimization")
    sys.dont_write_bytecode = True
    source = Path(source_plan).resolve(strict=True)
    request = Path(request).resolve(strict=True)
    output = Path(output_plan).resolve()
    if revision not in CANDIDATES:
        raise ValueError("Only the registered v2 and c2 candidates can be built")
    original_inventory = _safe_package_files(source)
    if _sha(request) != REQUEST_SHA256:
        raise ValueError("Revision request differs from explicit fixed authority")
    if output.exists() or output.is_relative_to(source) or source.is_relative_to(output):
        raise ValueError("Candidate needs a fresh path separate from the original source")
    output.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=".protocol-revision-", dir=output.parent))
    # Failed stages are intentionally retained with their logs for diagnosis.
    shutil.copytree(source, staging, dirs_exist_ok=True)
    retained = staging / "revision_sources/v1"
    shutil.copytree(source, retained)
    shutil.copy2(request, staging / "revision_sources/REQUEST.md")
    original_config = _json(source / "config/SR_F3_CE.json")
    _write_json(staging / "config/SR_F3_CE.json", revision_config(original_config, revision))
    for relative, text in _expected_revised_files(source, revision).items():
        (staging / relative).write_text(text, encoding="utf-8")
    checks = {}
    checks["build"] = _run(
        [sys.executable, "-B", "reference/build_manifest.py", "manifests"],
        staging,
        staging / "validation/REVISION_BUILD_STDOUT.txt",
    )
    difference = validate_revision_manifests(source / "manifests", staging / "manifests", revision)
    with tempfile.TemporaryDirectory(prefix="srf3ce-generator-rebuild-") as temporary:
        checks["rebuild"] = _run(
            [sys.executable, "-B", "reference/build_manifest.py", temporary],
            staging,
            staging / "validation/REVISION_REBUILD_STDOUT.txt",
        )
        rebuilt = _inventory(temporary)
        if rebuilt != _inventory(staging / "manifests"):
            raise ValueError("Actual reference generator rebuild is not byte-identical")
        checks["byte_identical_rebuild"] = rebuilt
    checks["tests"] = _run(
        [
            sys.executable,
            "-B",
            "-m",
            "pytest",
            "-q",
            "-c",
            "/dev/null",
            "-p",
            "no:cacheprovider",
            "tests",
        ],
        staging,
        staging / "validation/REVISION_REFERENCE_TESTS.txt",
    )
    _write_json(staging / "validation/REVISION_CPU_CHECKS.json", checks)
    diff = "".join(
        difflib.unified_diff(
            (CONTRACT_V1 + "\n").splitlines(keepends=True),
            (contract_for_revision(revision) + "\n").splitlines(keepends=True),
            fromfile="CONTRACT_v1",
            tofile="CONTRACT_" + revision,
        )
    )
    (staging / "validation/REVISION_CONTRACT_DIFF.txt").write_text(diff, encoding="utf-8")
    receipt = {
        "schema_version": 1,
        "status": "CANDIDATE_CPU_VALIDATED_UNSELECTED",
        "protocol_revision": revision,
        "original_package_manifest_sha256": ORIGINAL_PACKAGE_SHA256,
        "request_sha256": REQUEST_SHA256,
        "original_plan_files": original_inventory,
        "contract_sha256": hashlib.sha256(contract_for_revision(revision).encode()).hexdigest(),
        "teacher_serialization": TEACHER_SERIALIZATION,
        "teacher_mask_serialization_id": "indent_2",
        "protocol_prefills": {
            protocol: prefill_for(protocol, revision)
            for protocol in ("structured", "answer_only", "natural_work")
        },
        "manifest_difference": difference,
        "reference_validation": checks,
        "decision_rule": DECISION_RULE,
        "original_validation_logs_are_v1_only": True,
        "text_difference_disclosure": {
            "provided_v2_is_authoritative": True,
            "true_facts_became_true_chart_facts": revision == "v2",
            "optional_work_sentence_reworded_and_quoted": revision == "v2",
            "external_tools_sentence_moved": revision == "v2",
            "trailing_fact_literal_removed": revision == "v2",
            "c2_retains_v1_contract": revision == "c2",
        },
        "production_scorer_modified": False,
        "source_tools_sha256": {
            "protocol_revision.py": _sha(__file__),
            "prompts.py": _sha(Path(__file__).with_name("prompts.py")),
        },
        "new_model_calls": 0,
        "new_training_steps": 0,
    }
    _write_json(staging / "PROTOCOL_REVISION.json", receipt)
    inventory = _inventory(staging)
    inventory.pop("PACKAGE_SHA256.json")
    _write_json(staging / "PACKAGE_SHA256.json", inventory)
    verified = verify_revision_package(staging, source_plan_dir=source)
    if _safe_package_files(source) != original_inventory:
        raise ValueError("Original V1 package changed during candidate preparation")
    if output.exists():
        raise FileExistsError("Candidate appeared during build; immutable output was not replaced")
    staging.rename(output)
    return {**verified, "plan_path": str(output)}
